-- Phase 7 additive migration: benchmark intelligence + persistent risk history.
-- SAFETY: additive only. No existing table is altered destructively; no rows
-- in any existing table are touched. New tables get FK + UNIQUE + CHECK guards.

-- ---------------------------------------------------------------- benchmarks
CREATE TABLE IF NOT EXISTS benchmarks (
  benchmark_id  SERIAL PRIMARY KEY,
  symbol        VARCHAR(30)  NOT NULL,
  name          VARCHAR(100) NOT NULL,
  exchange      VARCHAR(20)  NOT NULL DEFAULT 'NSE',
  data_source   VARCHAR(20)  NOT NULL DEFAULT 'YAHOO',
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP(6) NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMP(6) NOT NULL DEFAULT NOW(),
  CONSTRAINT benchmarks_symbol_exchange_unique UNIQUE (symbol, exchange)
);

-- ---------------------------------------------------------- benchmark_prices
CREATE TABLE IF NOT EXISTS benchmark_prices (
  benchmark_price_id SERIAL PRIMARY KEY,
  benchmark_id  INTEGER      NOT NULL,
  price_date    DATE         NOT NULL,
  open_price    NUMERIC(18,2),
  high_price    NUMERIC(18,2),
  low_price     NUMERIC(18,2),
  close_price   NUMERIC(18,2) NOT NULL,
  volume        BIGINT,
  data_source   VARCHAR(20)  NOT NULL DEFAULT 'YAHOO',
  created_at    TIMESTAMP(6) NOT NULL DEFAULT NOW(),
  CONSTRAINT benchmark_prices_benchmark_fk
    FOREIGN KEY (benchmark_id) REFERENCES benchmarks (benchmark_id)
    ON DELETE CASCADE ON UPDATE NO ACTION,
  CONSTRAINT benchmark_prices_benchmark_date_unique UNIQUE (benchmark_id, price_date),
  CONSTRAINT benchmark_prices_close_positive CHECK (close_price > 0)
);

CREATE INDEX IF NOT EXISTS idx_benchmark_prices_date
  ON benchmark_prices (benchmark_id, price_date);

-- ---------------------------------------------------- portfolio_risk_snapshots
-- Derived daily risk metrics (one per portfolio/day/version). Calculation
-- inputs live in stock_prices/benchmark_prices; these rows are cache only.
CREATE TABLE IF NOT EXISTS portfolio_risk_snapshots (
  snapshot_id            SERIAL PRIMARY KEY,
  portfolio_id           INTEGER      NOT NULL,
  snapshot_date          DATE         NOT NULL,
  calculation_version    VARCHAR(20)  NOT NULL DEFAULT 'risk-v1',
  volatility             NUMERIC(10,6),
  downside_deviation     NUMERIC(10,6),
  sharpe                 NUMERIC(10,6),
  sortino                NUMERIC(10,6),
  calmar                 NUMERIC(10,6),
  max_drawdown           NUMERIC(10,6),
  var_95                 NUMERIC(10,6),
  var_99                 NUMERIC(10,6),
  cvar_95                NUMERIC(10,6),
  beta                   NUMERIC(10,6),
  alpha                  NUMERIC(10,6),
  hhi                    NUMERIC(10,6),
  effective_positions    NUMERIC(10,4),
  diversification_ratio  NUMERIC(10,6),
  benchmark_symbol       VARCHAR(30),
  observation_count      INTEGER,
  data_source            VARCHAR(20),
  priced_as_of           DATE,
  created_at             TIMESTAMP(6) NOT NULL DEFAULT NOW(),
  CONSTRAINT risk_snapshots_portfolio_fk
    FOREIGN KEY (portfolio_id) REFERENCES portfolios (portfolio_id)
    ON DELETE CASCADE ON UPDATE NO ACTION,
  -- Same portfolio/day/version never stored twice (idempotent snapshots).
  CONSTRAINT risk_snapshots_unique UNIQUE (portfolio_id, snapshot_date, calculation_version),
  CONSTRAINT risk_snapshots_version_ck CHECK (calculation_version <> '')
);

CREATE INDEX IF NOT EXISTS idx_risk_snapshots_portfolio_date
  ON portfolio_risk_snapshots (portfolio_id, snapshot_date DESC);

